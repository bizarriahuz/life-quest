// Writes schema.sql (the D1 database) from functions/_lib/schema.js. Run: node scripts/gen-schema.mjs
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { TABLES, COLS, pkOf } from '../functions/_lib/schema.js';

const SQLTYPE = { text: 'text', int: 'integer', num: 'real', bool: 'integer', date: 'text', time: 'text', ts: 'text', uuid: 'text', json: 'text' };
const lit = (c) => {
  const d = c.def;
  if (d === undefined || d === 'uuid') return '';
  if (d === 'now') return " default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))";
  if (d === 'today') return " default (date('now'))";
  if (d === '[]') return " default '[]'";
  return ` default ${d}`;
};

const out = [`-- LIFE QUEST — Cloudflare D1 database. Generated by scripts/gen-schema.mjs from functions/_lib/schema.js; don't edit by hand.
-- Safe to run again (everything is "if not exists"). Dates 'YYYY-MM-DD', times 'HH:MM:SS', timestamps ISO-8601 UTC,
-- booleans 0/1, lists/objects as JSON text. Access rules are enforced by the API (functions/api), not the database.

-- ---------- accounts ----------
create table if not exists users (
  id                 text primary key,
  email              text not null unique collate nocase,
  password_hash      text not null,
  email_confirmed_at text,
  created_at         text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  last_sign_in_at    text,
  last_seen_at       text
);
create table if not exists sessions (
  token_hash text primary key,
  user_id    text not null references users(id) on delete cascade,
  created_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  last_seen  text
);
create index if not exists sessions_user on sessions(user_id);
-- one-use links sent by email (confirm sign-up, reset password)
create table if not exists email_tokens (
  token_hash text primary key,
  user_id    text not null references users(id) on delete cascade,
  kind       text not null check (kind in ('confirm','reset')),
  expires_at text not null,
  created_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
create index if not exists email_tokens_user on email_tokens(user_id, kind);
-- simple rate limits (sign-ins, sign-ups, emails) by key
create table if not exists hits (
  key text not null,
  at  text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
create index if not exists hits_key on hits(key, at);
create table if not exists meta (key text primary key, value text);
create table if not exists app_admins (user_id text primary key references users(id) on delete cascade);
-- bumps whenever anything in a shared project changes (the app polls this instead of realtime)
create table if not exists project_versions (project_id text primary key, v integer not null default 0);
`];

// parents referenced as (id, user_id) need that pair to be unique
const parents = new Set();
for (const d of Object.values(TABLES)) for (const [, [p, how]] of Object.entries(d.refs || {})) if (how === 'cascade') parents.add(p);

const triggers = [];
for (const [t, d] of Object.entries(TABLES)) {
  const cols = COLS[t];
  const lines = Object.entries(cols).map(([k, c]) => `  ${k.padEnd(14)} ${SQLTYPE[c.type]}${c.required ? ' not null' : ''}${lit(c)}`);
  const pk = pkOf(t);
  lines.push(`  primary key (${[].concat(pk).join(', ')})`);
  if (d.owner) lines.push(`  foreign key (${d.owner}) references users(id) on delete cascade`);
  if (parents.has(t)) lines.push('  unique (id, user_id)');
  for (const u of d.unique || []) lines.push(`  unique (${u.join(', ')})`);
  for (const [col, [p, how]] of Object.entries(d.refs || {})) {
    if (how === 'cascade') lines.push(`  foreign key (${col}, user_id) references ${p}(id, user_id) on delete cascade`);
    else triggers.push(`create trigger if not exists ${t}_${col}_null after delete on ${p} begin update ${t} set ${col} = null where ${col} = old.id; end;`);
  }
  if (t === 'project_members') lines.push('  foreign key (project_id) references projects(id) on delete cascade', '  foreign key (user_id) references users(id) on delete cascade');
  if (t === 'project_invites') lines.push('  foreign key (project_id) references projects(id) on delete cascade', '  foreign key (created_by) references users(id) on delete cascade');
  if (t === 'projects') lines.push('  foreign key (owner_id) references users(id) on delete cascade');
  if (t === 'project_entries') {
    lines.push('  foreign key (project_id) references projects(id) on delete cascade');
    for (const c of ['author_id', 'paid_by', 'assignee_id', 'done_by']) lines.push(`  foreign key (${c}) references users(id) on delete set null`);
  }
  if (t === 'project_comments' || t === 'project_reactions') {
    lines.push('  foreign key (project_id) references projects(id) on delete cascade', '  foreign key (entry_id) references project_entries(id) on delete cascade');
    lines.push(t === 'project_comments' ? '  foreign key (author_id) references users(id) on delete set null' : '  foreign key (user_id) references users(id) on delete cascade');
  }
  if (t === 'feedback') lines.push('  foreign key (user_id) references users(id) on delete set null');
  out.push(`create table if not exists ${t} (\n${lines.join(',\n')}\n);`);
  if (d.owner && t !== 'profiles') out.push(`create index if not exists ${t}_user_created on ${t}(user_id, created_at);`);
}
out.push(`
create index if not exists project_members_user on project_members(user_id);
create index if not exists project_invites_project on project_invites(project_id);
create index if not exists project_entries_project on project_entries(project_id, created_at);
create index if not exists project_entries_author on project_entries(author_id, created_at);
create unique index if not exists project_entries_answer_once on project_entries(project_id, author_id, title) where kind = 'answer';
create index if not exists project_comments_entry on project_comments(project_id, entry_id, created_at);
create index if not exists project_reactions_project on project_reactions(project_id, entry_id);
create index if not exists feedback_created on feedback(created_at);
create index if not exists feedback_user on feedback(user_id, created_at);
create index if not exists transactions_user_day on transactions(user_id, occurred_on);
create index if not exists calendar_events_user_day on calendar_events(user_id, starts_on);
`);
out.push(...triggers);
const sql = out.join('\n') + '\n';
writeFileSync(new URL('../schema.sql', import.meta.url), sql);
// The API applies this itself when it changes (functions/_middleware.js), so nothing has to be run by hand.
const version = createHash('sha256').update(sql).digest('hex').slice(0, 16);
writeFileSync(new URL('../functions/_lib/schema-sql.js', import.meta.url),
  `// Generated by scripts/gen-schema.mjs — don't edit.\nexport const VERSION = '${version}';\nexport const SQL = ${JSON.stringify(sql)};\n`);
console.log('schema.sql written:', Object.keys(TABLES).length, 'app tables');
